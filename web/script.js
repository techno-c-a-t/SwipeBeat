const demoTracks = [
  { title: "Midnight City", artist: "M83" },
  { title: "Starboy", artist: "The Weeknd" },
  { title: "Get Lucky", artist: "Daft Punk" }
];

let currentTrackIdx = 0;
let approvedCount = 0;
let rejectedCount = 0;

const card = document.getElementById('interactive-card');
const titleEl = document.getElementById('track-title');
const artistEl = document.getElementById('track-artist');
const indexEl = document.getElementById('demo-index');
const approvedEl = document.getElementById('count-approved');
const rejectedEl = document.getElementById('count-rejected');
const badgeApprove = document.getElementById('badge-approve');
const badgeReject = document.getElementById('badge-reject');

function updateTrackUI() {
  if (!titleEl) return;
  const track = demoTracks[currentTrackIdx];
  titleEl.textContent = track.title;
  artistEl.textContent = track.artist;
  indexEl.textContent = `Track ${currentTrackIdx + 1} of ${demoTracks.length}`;
}

function triggerSwipe(direction) {
  if (!card) return;

  if (direction === 'up') {
    if (badgeApprove) badgeApprove.style.opacity = '1';
    card.classList.add('swipe-up');
    approvedCount++;
    if (approvedEl) approvedEl.textContent = approvedCount;
  } else {
    if (badgeReject) badgeReject.style.opacity = '1';
    card.classList.add('swipe-down');
    rejectedCount++;
    if (rejectedEl) rejectedEl.textContent = rejectedCount;
  }

  setTimeout(() => {
    card.style.transition = 'none';
    card.classList.remove('swipe-up', 'swipe-down');
    if (badgeApprove) badgeApprove.style.opacity = '0';
    if (badgeReject) badgeReject.style.opacity = '0';
    
    currentTrackIdx = (currentTrackIdx + 1) % demoTracks.length;
    updateTrackUI();

    setTimeout(() => {
      card.style.transition = 'transform 0.4s cubic-bezier(0.175, 0.885, 0.32, 1.275), opacity 0.3s ease';
    }, 50);
  }, 350);
}

