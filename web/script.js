// ==========================================================================
// AUTOMATIC LANGUAGE DETECTION
// ==========================================================================
function detectLanguage() {
  const saved = localStorage.getItem('swipebeat_lang');
  if (saved && translations[saved]) return saved;

  const browserLangs = navigator.languages || [navigator.language || navigator.userLanguage];
  const isBelarusian = browserLangs.some(l => l.toLowerCase().includes('be') || l.toLowerCase().includes('by')) 
                    || (Intl.DateTimeFormat().resolvedOptions().timeZone || '').includes('Minsk');

  return isBelarusian ? 'be' : 'en';
}

let currentLang = detectLanguage();

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('swipebeat_lang', lang);
  document.getElementById('currentLangLabel').textContent = langLabels[lang];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      if (key === 'docTitle') {
        document.title = translations[lang][key];
      } else {
        el.textContent = translations[lang][key];
      }
    }
  });

  const langDropdown = document.getElementById('langDropdown');
  if (langDropdown) langDropdown.classList.remove('open');
}

